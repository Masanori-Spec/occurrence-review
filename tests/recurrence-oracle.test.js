  test(`dateutil oracle ${index + 1}: ${fixture.start} ${fixture.rule}`, () => {
    const input = [
      "BEGIN:VCALENDAR",
      "VERSION:2.0",
      "PRODID:-//Oracle test//EN",
      "BEGIN:VEVENT",
      `UID:oracle-${index}`,
      "DTSTAMP:20240101T000000Z",
      `DTSTART:${fixture.start}`,
      "DURATION:PT1H",
      `RRULE:${fixture.rule}`,
      "END:VEVENT",
      "END:VCALENDAR",
      "",
    ].join("\r\n");
    const result = compareCalendars(empty, input, {
      start: "2024-01-01",
      end: "2033-01-01",
    });
    assert.equal(result.complete, true, JSON.stringify(result.diagnostics));
    const actual = result.changes.map((row) => row.after.start).sort();
    assert.deepEqual(actual, fixture.expected);
    assert.equal(result.summary.added, fixture.expected.length);
    assert.equal(result.summary.removed, 0);
    assert.equal(
      new Set(result.changes.map((row) => row.id)).size,
      fixture.expected.length,
    );
  });
